import { Router } from "express";
import * as controller from "../controllers/ownerController.js";
import { authMiddleware, logActionsAsOwner, ownerOnly } from "../middleware/authMiddleware.js";
import { aiDraftUpload, bulkAiDraftUpload, previewUpload, upload } from "../middleware/upload.js";

export const ownerRoutes = Router();
ownerRoutes.use(authMiddleware, ownerOnly, logActionsAsOwner);
ownerRoutes.get("/support", controller.getSupport);
ownerRoutes.get("/preview-styles", controller.listPreviewStyles);
ownerRoutes.get("/stores", controller.listStores);
ownerRoutes.get("/stores/:storeId", controller.getStore);
ownerRoutes.patch("/stores/:storeId", controller.updateStore);
ownerRoutes.post("/stores/:storeId/logo", upload.single("logo"), controller.updateStoreLogo);
ownerRoutes.get("/stores/:storeId/analytics", controller.getAnalytics);
ownerRoutes.get("/stores/:storeId/subscription", controller.getSubscription);
ownerRoutes.post("/stores/:storeId/online-payments", controller.startOnlinePayment);
ownerRoutes.post("/stores/:storeId/online-payments/:paymentId/check", controller.checkOnlinePayment);
ownerRoutes.post("/stores/:storeId/packages/:packageId/request", controller.requestPackage);
ownerRoutes.delete("/stores/:storeId/package-orders/:orderId", controller.withdrawPackageRequest);
ownerRoutes.get("/stores/:storeId/products", controller.listProducts);
ownerRoutes.get("/stores/:storeId/categories", controller.listCategories);
ownerRoutes.post("/stores/:storeId/products/ai-draft", aiDraftUpload.fields([{ name: "voice", maxCount: 1 }, { name: "images", maxCount: 8 }]), controller.createProductDraft);
ownerRoutes.post("/stores/:storeId/products/bulk-ai-draft", bulkAiDraftUpload.fields([{ name: "voice", maxCount: 1 }, { name: "images", maxCount: 40 }]), controller.createBulkProductDraft);
// Before /products/:id, which would take «bulk-ai-draft» for a product id.
ownerRoutes.get("/stores/:storeId/products/bulk-ai-draft", controller.listBulkDrafts);
ownerRoutes.get("/stores/:storeId/products/bulk-ai-draft/:draftId", controller.getBulkDraft);
ownerRoutes.get("/stores/:storeId/products/bulk-ai-draft/:draftId/photos/:index", controller.getBulkDraftPhoto);
ownerRoutes.delete("/stores/:storeId/products/bulk-ai-draft/:draftId", controller.deleteBulkDraft);
ownerRoutes.post("/stores/:storeId/products/ai-preview", previewUpload.single("image"), controller.createPreview);
ownerRoutes.post("/stores/:storeId/products", controller.createProduct);
ownerRoutes.post("/stores/:storeId/products/bulk", controller.bulkProducts);
ownerRoutes.get("/stores/:storeId/products/:id", controller.getProduct);
ownerRoutes.patch("/stores/:storeId/products/:id", controller.updateProduct);
ownerRoutes.delete("/stores/:storeId/products/:id", controller.deleteProduct);
ownerRoutes.post("/stores/:storeId/products/:id/images", upload.single("image"), controller.addImage);
ownerRoutes.patch("/stores/:storeId/products/:id/images/order", controller.reorderImages);
ownerRoutes.delete("/stores/:storeId/products/:id/images/:imageId", controller.deleteImage);
